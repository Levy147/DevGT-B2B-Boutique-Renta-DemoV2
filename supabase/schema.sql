-- ------------------------------------------------------------
-- 1. Tablas
-- ------------------------------------------------------------

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  emoji text default '♡',
  blurb text default '',
  image text default '',
  sort_order int default 0,
  created_at timestamptz default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text unique,
  name text not null,
  slug text,
  category_id bigint references public.categories(id) on delete set null,
  price numeric(10,2) not null default 0,
  old_price numeric(10,2),
  badge text default '',
  rating numeric(3,2) default 5,
  reviews int default 0,
  description text default '',
  details jsonb default '[]'::jsonb,
  sizes text[] default '{}',
  colors text[] default '{}',
  image text default '',
  tint int default 0,
  stock int default 0,
  active boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'cliente',
  created_at timestamptz default now()
);

-- ------------------------------------------------------------
-- 2. Índices
-- ------------------------------------------------------------

create index if not exists products_category_idx on public.products(category_id);
create index if not exists products_active_idx on public.products(active);
create index if not exists products_sku_idx on public.products(sku);

-- ------------------------------------------------------------
-- 3. Funciones y triggers
-- ------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at
before update on public.products
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (new.id, new.email, 'cliente')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- Devuelve true si el usuario autenticado es admin.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

-- ------------------------------------------------------------
-- 4. Row Level Security (RLS)
-- ------------------------------------------------------------

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.profiles enable row level security;

-- Lectura pública de categorías
drop policy if exists "categories_read" on public.categories;
create policy "categories_read"
on public.categories for select
using (true);

-- Lectura pública de productos activos (admin ve todos)
drop policy if exists "products_read" on public.products;
create policy "products_read"
on public.products for select
using (active = true or public.is_admin());

-- Escritura solo admin
drop policy if exists "categories_admin_write" on public.categories;
create policy "categories_admin_write"
on public.categories for all to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "products_admin_write" on public.products;
create policy "products_admin_write"
on public.products for all to authenticated
using (public.is_admin())
with check (public.is_admin());

-- Perfiles: cada usuario ve el suyo; admin ve todos
drop policy if exists "profiles_self_read" on public.profiles;
create policy "profiles_self_read"
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles_admin_write" on public.profiles;
create policy "profiles_admin_write"
on public.profiles for all to authenticated
using (public.is_admin())
with check (public.is_admin());

-- ------------------------------------------------------------
-- 5. Permisos (Supabase)
-- ------------------------------------------------------------

grant usage on schema public to anon, authenticated;
grant select on public.categories to anon, authenticated;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.categories to authenticated;
grant insert, update, delete on public.products to authenticated;
grant select, update on public.profiles to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.is_admin() to anon, authenticated;

